#!/usr/bin/env python3
"""Write the committed snapshot of the trading pipeline map (lane PIPELINE-MAP, 2026-11-14).

The map is GENERATED by ``src/runtime/pipeline_map.py`` from the hand-written skeleton
``docs/reference/trading-pipeline-map.skeleton.md`` plus the sources of truth (rosters, strategy status,
evidence records, the journal's performance route, served ML models, mandates, unit files, the TP guard).
The Work tab builds it live (``GET /api/bot/work/pipeline-map``); this script writes the same output to
``docs/reference/trading-pipeline-map.md`` as a snapshot. The weekly doc-freshness check re-runs it.

A REPORT, not a guard: it never fails CI.

Usage:
    python3 scripts/ops/pipeline_map_numbers.py               # live numbers fetched from the public API
    python3 scripts/ops/pipeline_map_numbers.py --offline     # skip the API; live columns read "—" (not read)
    python3 scripts/ops/pipeline_map_numbers.py --live-json f # use a saved /api/bot/performance payload
    python3 scripts/ops/pipeline_map_numbers.py --stdout      # print instead of writing the snapshot
"""
from __future__ import annotations

import argparse
import json
import os
import ssl
import sys
import urllib.request
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from src.runtime import pipeline_map

API = os.environ.get("PIPELINE_MAP_API", "https://ict-bot.duckdns.org") + "/api/bot/performance?window=all"


def fetch_live(path: str | None, offline: bool) -> tuple[dict[str, Any] | None, str]:
    if offline:
        return None, "not read (--offline)"
    try:
        if path:
            return json.loads(Path(path).read_text(encoding="utf-8")), "read"
        ctx = ssl.create_default_context(cafile=os.environ.get("SSL_CERT_FILE") or os.environ.get("REQUESTS_CA_BUNDLE"))
        req = urllib.request.Request(API, headers={"User-Agent": "pipeline-map"})
        with urllib.request.urlopen(req, timeout=30, context=ctx) as r:
            return json.loads(r.read().decode("utf-8")), "read"
    except (OSError, ValueError) as e:  # unreadable is a state, never a zero
        return None, f"unreadable ({type(e).__name__})"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--live-json")
    ap.add_argument("--stdout", action="store_true")
    a = ap.parse_args()
    live, state = fetch_live(a.live_json, a.offline)
    out = pipeline_map.build(REPO, live=live, live_state=state)
    if a.stdout:
        print(out)
        return 0
    (REPO / pipeline_map.SNAPSHOT_REL).write_text(out, encoding="utf-8")
    print(f"wrote {pipeline_map.SNAPSHOT_REL} ({len(out)} B; live read-state: {state})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
