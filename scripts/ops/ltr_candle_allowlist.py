#!/usr/bin/env python3
# wiring: manual-only - run by AM-OPS (LTR-GRADER-COVERAGE option (b)) when a live roster changes; no schedule, no CI gate.
"""LTR-GRADER-COVERAGE option (b), manager pick 2026-11-13: committed per-leg candles readable ON THE VM, no network.

The live-review pricer (scripts/research/live_review_outcomes.py) replays each live leg's corpus over the leg's own
committed research candles (find_candles). The VM's sparse checkout (deploy/vm-sparse-checkout) hides every
comms/research/**/candles/ file, so on the VM find_candles returns None and the pricer falls back to a network fetch
that is blocked or rate-limited there (Bybit 403, Yahoo 429). Copying the files would duplicate ~77 MB in the repo.
Instead this writes, between two markers in deploy/vm-sparse-checkout, one RE-INCLUDE line per exact candle file the
pricer selects for a leg on a live roster (git's non-cone sparse checkout honours an exact-file re-include under an
excluded directory; tested). Nothing is copied; the files are the committed corpora the evidence was built on.

    ltr_candle_allowlist.py            # rewrite the block in deploy/vm-sparse-checkout
    ltr_candle_allowlist.py --check    # exit 1 when the block differs from what the rosters need (tool only)
    ltr_candle_allowlist.py --json     # the selection and the legs with NO committed candles

Legs whose symbol has no committed candle file anywhere (today: equity/ETF/futures legs) are listed as `missing`;
they still need a networked source and are NOT solved here.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Tuple

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

PATTERNS = REPO / "deploy" / "vm-sparse-checkout"
BEGIN = "# >>> LTR-CANDLE-ALLOWLIST begin (generated by scripts/ops/ltr_candle_allowlist.py; do not hand-edit)"
END = "# <<< LTR-CANDLE-ALLOWLIST end"


def live_legs(accounts_path: Path = REPO / "config" / "accounts.yaml") -> List[str]:
    import yaml
    a = yaml.safe_load(accounts_path.read_text(encoding="utf-8")) or {}
    accs = a.get("accounts", a)
    out = set()
    for cfg in accs.values():
        if isinstance(cfg, dict) and cfg.get("mode") == "live":
            for r in cfg.get("strategies") or []:
                name = r if isinstance(r, str) else (r.get("name") or r.get("strategy"))
                if name:
                    out.add(str(name))
    return sorted(out)


def select(legs: List[str]) -> Tuple[Dict[str, List[str]], List[str]]:
    """({repo-relative candle path: [leg:symbol, ...]}, [leg:symbol:tf with no committed candles])."""
    from scripts.research import live_review_outcomes as L
    files: Dict[str, List[str]] = {}
    missing: List[str] = []
    for leg in legs:
        ev = REPO / "comms" / "strategy_evidence" / f"{leg}.json"
        if not ev.is_file():
            continue
        try:
            trades, src = L.load_trades(leg, corpus="auto")
        except Exception:  # noqa: BLE001 -- a leg with no loadable corpus has nothing to price; not this tool's job
            continue
        tf = json.loads(ev.read_text(encoding="utf-8")).get("timeframe")
        tf = str(tf).split()[0] if tf else None
        if not tf:
            continue
        full = str(src).startswith(L.LTR_CORPUS_DIR)       # the pricer's own rule (main(): widest_span=full)
        for sym in sorted({str(t.get("symbol")) for t in trades if t.get("symbol")}):
            hit = L.find_candles(sym, tf, widest_span=full)
            if hit:
                rel = str(Path(hit).resolve().relative_to(REPO))
                files.setdefault(rel, []).append(f"{leg}:{sym}")
            else:
                missing.append(f"{leg}:{sym}:{tf}")
    return files, missing


def render_block(files: Dict[str, List[str]]) -> str:
    lines = [BEGIN,
             "# Re-includes ONLY the exact committed candle files the live-review pricer selects for legs on a live",
             "# roster (LTR-GRADER-COVERAGE option (b)). Everything else under comms/research stays excluded above."]
    lines += [f"/{p}" for p in sorted(files)]
    lines.append(END)
    return "\n".join(lines) + "\n"


def apply_block(text: str, block: str) -> str:
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return head + block + tail.lstrip("\n")
    return text.rstrip("\n") + "\n\n" + block


def main(argv: List[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    files, missing = select(live_legs())
    new = apply_block(PATTERNS.read_text(encoding="utf-8"), render_block(files))
    if a.json:
        print(json.dumps({"files": files, "missing": missing}, indent=1, sort_keys=True))
        return 0
    if a.check:
        same = new == PATTERNS.read_text(encoding="utf-8")
        print(f"ltr-candle-allowlist: {'OK' if same else 'DRIFT'} ({len(files)} files, {len(missing)} leg:symbol with no committed candles)")
        return 0 if same else 1
    PATTERNS.write_text(new, encoding="utf-8")
    print(f"ltr-candle-allowlist: wrote {len(files)} re-include line(s); {len(missing)} leg:symbol have no committed candles")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
