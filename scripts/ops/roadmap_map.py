#!/usr/bin/env python3
# wiring: scripts/ci/run_guards.py::roadmap-map-guard (--self-test, --check --base origin/main).
"""THE ROADMAP LOOP'S CHECKABLE ARTEFACT: milestone <-> checklist row <-> queue unit.

WHY (operator, 2026-10-11, row ROADMAP-LOOP): the roadmap is the high-level plan;
the work queue (checklist rows + research/queue units) is BUILT and PRIORITISED
FROM its milestones; outcomes are WRITTEN BACK to the roadmap and the architecture
map. Before this existed the link was prose: the 2026-09-24 E53 sweep found work
"landed as checklist rows that never name M39". This tool makes the link a field.

DATA
  docs/roadmap/milestones.yaml   goals + live milestones (hand-written status) + queue_rules
  checklist row  `roadmap`: [<milestone id>...]   set when the row is created
  checklist row  `writeback`: {"roadmap": str, "arch": str}   set when the row is CLOSED
  queue unit     `roadmap`: <id> | [<id>...]      (older units resolve through `queue_rules`)

COMMANDS
  --report                    where every milestone stands: live rows, queue units, orphans
  --render                    print the generated block for ROADMAP.md
  --write-roadmap             rewrite the block between the markers in ROADMAP.md
  --check [--base REF]        the guard (whole-store checks + diff-scoped enforcement)
  --backfill FILE             materialise the fallback mapping: set `roadmap` on live rows that lack it
                              (idempotent; goes through checklist.py)
  --self-test                 synthetic proof that every failure mode fails
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

MILESTONES = REPO / "docs" / "roadmap" / "milestones.yaml"
ROADMAP = REPO / "ROADMAP.md"
ARCH = REPO / "docs" / "ARCHITECTURE-CANONICAL.md"
QUEUE = REPO / "research" / "queue"
STORE_REL = "docs/claude/work/checklist"
BEGIN = "<!-- ROADMAP-LIVE:BEGIN (generated by scripts/ops/roadmap_map.py --write-roadmap; edit docs/roadmap/milestones.yaml) -->"
END = "<!-- ROADMAP-LIVE:END -->"
STATUSES = {"active", "dormant", "backlog", "closed"}
GLYPH = {"active": "🔄", "dormant": "📋", "backlog": "📋", "closed": "✅"}
CLOSED_ROW = {"done", "landed_unproven"}
LIVE_ROW = {"queued", "in_flight", "blocked", "landed_unproven"}


# ── loading ────────────────────────────────────────────────────────────────
def load_spec(path: Path = MILESTONES) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def as_list(v) -> list[str]:
    if v is None:
        return []
    return [str(x) for x in (v if isinstance(v, list) else [v])]


def load_rows() -> list[dict]:
    from src.runtime import checklist_store
    return checklist_store.load()["items"]


def load_units(root: Path = QUEUE) -> list[dict]:
    out = []
    for f in sorted([*root.glob("RQ-*.yaml"), *root.glob("blocked/RQ-*.yaml")]):
        try:
            u = yaml.safe_load(f.read_text(encoding="utf-8"))
        except yaml.YAMLError:
            continue
        if isinstance(u, dict) and u.get("id"):
            out.append(u)
    return out


def unit_milestones(u: dict, rules: list[dict]) -> list[str]:
    explicit = as_list(u.get("roadmap"))
    if explicit:
        return explicit
    title = str(u.get("title") or "")
    for r in rules:
        if r.get("theme") and r["theme"] != u.get("theme"):
            continue
        if r.get("title_re") and not re.search(r["title_re"], title):
            continue
        if r.get("theme") or r.get("title_re"):
            return [r["milestone"]]
    return []


# ── the mapping ────────────────────────────────────────────────────────────
def row_refs(r: dict, fallback: dict) -> list[str]:
    """The row's own `roadmap` field wins; the committed fallback mapping covers rows nobody tagged yet."""
    own = as_list(r.get("roadmap"))
    if own:
        return own
    fb = fallback.get(r["id"])
    return [fb] if fb else []


def load_fallback(spec: dict) -> dict:
    rel = spec.get("row_fallback")
    if not rel:
        return {}
    f = REPO / rel
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}


def build(spec: dict, rows: list[dict], units: list[dict], fallback: dict | None = None) -> dict:
    fallback = load_fallback(spec) if fallback is None else fallback
    ms = {m["id"]: m for m in spec["milestones"]}
    per = {i: {"rows_live": [], "rows_closed": [], "units_open": [], "units_done": []} for i in ms}
    orphan_rows, orphan_units, dangling = [], [], []
    for r in rows:
        refs = row_refs(r, fallback)
        st = r.get("state")
        for ref in refs:
            if ref not in ms:
                dangling.append(("row", r["id"], ref))
            elif st in LIVE_ROW:
                per[ref]["rows_live"].append(r["id"])
            elif st == "done":
                per[ref]["rows_closed"].append(r["id"])
        if not refs and st in LIVE_ROW:
            orphan_rows.append(r["id"])
    for u in units:
        refs = unit_milestones(u, spec.get("queue_rules") or [])
        st = u.get("status")
        for ref in refs:
            if ref not in ms:
                dangling.append(("unit", u["id"], ref))
            elif st in ("queued", "blocked"):
                per[ref]["units_open"].append(u["id"])
            elif st == "done":
                per[ref]["units_done"].append(u["id"])
        if not refs and st in ("queued", "blocked"):
            orphan_units.append(u["id"])
    return {"ms": ms, "per": per, "orphan_rows": orphan_rows,
            "orphan_units": orphan_units, "dangling": dangling}


def has_work(per: dict) -> bool:
    return bool(per["rows_live"] or per["units_open"])


def verdict(m: dict, per: dict) -> str:
    if has_work(per):
        return "OK"
    if m.get("no_rows_reason"):
        return "NONE-YET (reason given)"
    return "NEEDS-ROWS"


# ── report / render ────────────────────────────────────────────────────────
def report(spec: dict, built: dict, today: dt.date) -> str:
    out = ["# Roadmap <-> work-queue map", ""]
    cad = int(spec.get("review_cadence_days", 8))
    for gid, g in spec["goals"].items():
        out += [f"## {gid} {g['name']}", ""]
        out += ["| milestone | status | live rows | closed rows | open units | verdict | reviewed |",
                "|---|---|---|---|---|---|---|"]
        for m in spec["milestones"]:
            if m["goal"] != gid:
                continue
            p = built["per"][m["id"]]
            rv = m.get("reviewed")
            late = " **OVERDUE**" if rv and (today - _d(rv)).days > cad else ""
            out.append(f"| {m['id']} {m['name']} | {m['status']} | {len(p['rows_live'])} | "
                       f"{len(p['rows_closed'])} | {len(p['units_open'])} | {verdict(m, p)} | {rv}{late} |")
        out.append("")
    out += [f"**Orphan live rows (no `roadmap` ref): {len(built['orphan_rows'])}**", ""]
    out += [", ".join(built["orphan_rows"][:60]) or "none", ""]
    out += [f"**Orphan open queue units: {len(built['orphan_units'])}**", ""]
    out += [", ".join(built["orphan_units"][:60]) or "none", ""]
    out += [f"**Dangling refs: {len(built['dangling'])}**"] + [f"- {k} {i} -> {r}" for k, i, r in built["dangling"]]
    return "\n".join(out) + "\n"


def _d(v) -> dt.date:
    return v if isinstance(v, dt.date) else dt.date.fromisoformat(str(v))


def render(spec: dict) -> str:
    L = [BEGIN, "",
         "## Live roadmap — where we are on the way to the system goals", "",
         (f"> **Reviewed {spec['reviewed']} by the roadmap loop** "
          "([`manager` skill § The roadmap loop](.claude/skills/manager/SKILL.md)). "
          "This block is **generated** from [`docs/roadmap/milestones.yaml`](docs/roadmap/milestones.yaml) "
          "plus the `roadmap` field on checklist rows and queue units. Row/unit counts are deliberately NOT "
          "in this block — they move with every research-queue PR and would leave it stale; read them live with "
          "`python3 scripts/ops/roadmap_map.py --report`. A milestone with no work says so and why; "
          "a live row with no milestone is a defect. The historical record below this block is "
          "kept intact and is **context**; this block is the plan."), ""]
    for gid, g in spec["goals"].items():
        L += [f"### {gid} — {g['name']}", "", f"**Measure.** {g['measure']}  ", f"**Baseline.** {g['baseline']}", ""]
        L += ["| milestone | status | where we are | next | work note |", "|---|---|---|---|---|"]
        for m in spec["milestones"]:
            if m["goal"] != gid:
                continue
            # no counts here: they drift with every queue PR (see roadmap-guard-stale); --report has them
            work = f"**none yet** — {m.get('no_rows_reason', '')}" if m.get("no_rows_reason") else "—"
            L.append(f"| **{m['id']}** {m['name']} | {GLYPH[m['status']]} {m['status']} | "
                     f"{_cell(m['where'])} | {_cell(m['next'])} | {_cell(work)} |")
        L.append("")
    L += [("**Unmapped work** (live rows / open units with no milestone) is counted live by "
           "`python3 scripts/ops/roadmap_map.py --report`; backfill is part of the weekly pass."), "", END]
    return "\n".join(L)


def _cell(s: str) -> str:
    return re.sub(r"\s+", " ", str(s)).replace("|", "/").strip()


def write_roadmap(text: str) -> None:
    body = ROADMAP.read_text(encoding="utf-8")
    block = text
    if BEGIN in body:
        pre, rest = body.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        ROADMAP.write_text(pre + block + post, encoding="utf-8")
        return
    anchor = "## Core Principles"
    if anchor not in body:
        raise SystemExit("anchor '## Core Principles' not found in ROADMAP.md")
    pre, post = body.split(anchor, 1)
    ROADMAP.write_text(pre + block + "\n\n---\n\n" + anchor + post, encoding="utf-8")


# ── the guard ──────────────────────────────────────────────────────────────
def static_problems(spec: dict, built: dict, arch_text: str, roadmap_text: str | None) -> list[str]:
    bad: list[str] = []
    gids = set(spec["goals"])
    seen: set[str] = set()
    for m in spec["milestones"]:
        i = m["id"]
        if i in seen:
            bad.append(f"duplicate milestone id {i}")
        seen.add(i)
        if m.get("goal") not in gids:
            bad.append(f"{i}: goal {m.get('goal')!r} is not declared")
        if m.get("status") not in STATUSES:
            bad.append(f"{i}: status {m.get('status')!r} not in {sorted(STATUSES)}")
        for k in ("name", "where", "next", "reviewed"):
            if not m.get(k):
                bad.append(f"{i}: missing `{k}`")
        if not has_work(built["per"].get(i, {"rows_live": [], "units_open": []})) and not m.get("no_rows_reason"):
            bad.append(f"{i}: no live row or open unit and no `no_rows_reason` -- build rows from it, or say why none exist")
        for a in as_list(m.get("architecture")):
            if a not in arch_text:
                bad.append(f"{i}: architecture ref {a!r} not found in docs/ARCHITECTURE-CANONICAL.md")
    for kind, ident, ref in built["dangling"]:
        bad.append(f"{kind} {ident}: roadmap ref {ref!r} is not a milestone in milestones.yaml")
    for r in spec.get("queue_rules") or []:
        if r.get("milestone") not in seen:
            bad.append(f"queue_rules: milestone {r.get('milestone')!r} unknown")
    if roadmap_text is not None:
        want = render(spec)
        if BEGIN not in roadmap_text or want not in roadmap_text:
            bad.append("ROADMAP.md live block is stale -- run: python3 scripts/ops/roadmap_map.py --write-roadmap")
    return bad


def diff_problems(spec: dict, head_rows: dict, base_rows: dict, head_units: dict,
                  base_units: dict, seqs: dict) -> list[str]:
    """Enforcement is on what THIS diff touches, so an old row cannot redden an unrelated PR."""
    bad: list[str] = []
    floor = int(spec.get("enforce_from_seq", 10**9))
    for rid, r in head_rows.items():
        if int(seqs.get(rid, 0)) < floor:
            continue
        old = base_rows.get(rid)
        if old is not None and old.get("state") == r.get("state") and old.get("roadmap") == r.get("roadmap"):
            continue
        if not as_list(r.get("roadmap")):
            bad.append(f"row {rid}: new/changed row carries no `roadmap` milestone ref (docs/roadmap/milestones.yaml)")
        closing = r.get("state") in CLOSED_ROW and (old is None or old.get("state") != r.get("state"))
        if closing:
            w = r.get("writeback")
            if not (isinstance(w, dict) and str(w.get("roadmap") or "").strip() and str(w.get("arch") or "").strip()):
                bad.append(f"row {rid}: closing to {r['state']} needs `writeback` = "
                           '{"roadmap": "<milestone line you updated | none: reason>", '
                           '"arch": "<ARCHITECTURE section you updated | none: reason>"}')
    ufloor = str(spec.get("enforce_units_from", "99999999"))
    for uid, u in head_units.items():
        m = re.match(r"RQ-(\d{8})", uid)
        if not m or m.group(1) < ufloor or uid in base_units:
            continue
        if not as_list(u.get("roadmap")):
            bad.append(f"unit {uid}: new queue unit carries no `roadmap` milestone ref")
    return bad


def _git(*a: str) -> str:
    return subprocess.run(["git", *a], cwd=REPO, capture_output=True, text=True, check=False).stdout


def _diff_inputs(base: str):
    changed = [p for p in _git("diff", "--name-only", base, "--", STORE_REL, "research/queue").split("\n") if p]
    head_rows, base_rows, seqs, head_units, base_units = {}, {}, {}, {}, {}
    for p in changed:
        f = REPO / p
        if p.startswith(STORE_REL) and p.endswith(".json") and not Path(p).name.startswith("_"):
            if f.exists():
                d = json.loads(f.read_text(encoding="utf-8"))
                head_rows[d["id"]] = d
                seqs[d["id"]] = d.get("_seq", 0)
            old = _git("show", f"{base}:{p}")
            if old.strip():
                od = json.loads(old)
                base_rows[od["id"]] = od
        elif p.startswith("research/queue/RQ-") and p.endswith(".yaml"):
            uid = Path(p).stem
            if f.exists():
                head_units[uid] = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
            if _git("show", f"{base}:{p}").strip():
                base_units[uid] = {}
    return head_rows, base_rows, head_units, base_units, seqs


def check(base: str | None) -> int:
    # The diff-scoped verdict is about the COMMITTED tree; say so when that is
    # not the tree you edited (shared notice, see check_document_index.py).
    sys.path.insert(0, str(REPO / "scripts" / "ci"))
    import _dirty_tree
    _dirty_tree.warn()
    spec = load_spec()
    built = build(spec, load_rows(), load_units())
    bad = static_problems(spec, built, ARCH.read_text(encoding="utf-8"), ROADMAP.read_text(encoding="utf-8"))
    if base:
        bad += diff_problems(spec, *_diff_inputs(base))
    else:
        print("note: no --base given; diff-scoped enforcement skipped")
    for b in bad:
        print("FAIL:", b)
    print(f"roadmap-map: {len(spec['milestones'])} milestones, {len(built['orphan_rows'])} orphan live rows, "
          f"{len(built['orphan_units'])} orphan open units -- {'FAIL' if bad else 'ok'}")
    return 1 if bad else 0


def self_test() -> int:
    spec = {"reviewed": "2026-10-11", "enforce_from_seq": 10, "enforce_units_from": "20261012",
            "goals": {"G1": {"name": "g", "measure": "m", "baseline": "b"}},
            "milestones": [
                {"id": "A", "goal": "G1", "name": "a", "status": "active", "where": "w", "next": "n", "reviewed": "2026-10-11"},
                {"id": "B", "goal": "G1", "name": "b", "status": "dormant", "where": "w", "next": "n", "reviewed": "2026-10-11"}],
            "queue_rules": [{"milestone": "A", "title_re": "alpha"}]}
    rows = [{"id": "R1", "state": "queued", "roadmap": ["A"]}, {"id": "R2", "state": "queued"},
            {"id": "R3", "state": "queued", "roadmap": ["Z"]}]
    units = [{"id": "RQ-20261001-1", "status": "queued", "title": "alpha sweep"},
             {"id": "RQ-20261001-2", "status": "queued", "title": "other"}]
    built = build(spec, rows, units)
    assert built["orphan_rows"] == ["R2"] and built["orphan_units"] == ["RQ-20261001-2"], built
    assert built["dangling"] == [("row", "R3", "Z")], built["dangling"]
    bad = static_problems(spec, built, "", None)
    assert any("B: no live row" in b for b in bad), bad            # active-or-not, empty needs a reason
    assert any("'Z'" in b for b in bad), bad                        # dangling ref
    spec["milestones"][1]["no_rows_reason"] = "dormant since X"
    built = build(spec, rows[:1], units[:1])
    assert static_problems(spec, built, "", None) == [], static_problems(spec, built, "", None)
    spec["milestones"][0]["architecture"] = ["No such heading"]
    assert any("architecture ref" in b for b in static_problems(spec, built, "x", None))
    spec["milestones"][0].pop("architecture")
    stale = static_problems(spec, built, "", "no block here")
    assert any("stale" in b for b in stale), stale
    ok_text = "pre\n" + render(spec) + "\npost"
    assert static_problems(spec, built, "", ok_text) == []
    # (b) count-only drift (queue PRs add/retire units, orphan counts move) must NOT report stale
    more = units[:1] + [{"id": "RQ-20261001-3", "status": "queued", "title": "alpha two"},
                        {"id": "RQ-20261001-4", "status": "queued", "title": "stray"}]
    drift = build(spec, rows[:1] + [{"id": "R9", "state": "queued"}], more)
    assert drift["per"]["A"]["units_open"] != built["per"]["A"]["units_open"] and drift["orphan_units"] != built["orphan_units"]
    assert not any("stale" in b for b in static_problems(spec, drift, "", ok_text)), "count drift reported stale"
    # (a) a milestones.yaml text change must still report stale
    spec["milestones"][0]["where"] = "changed text"
    assert any("stale" in b for b in static_problems(spec, built, "", ok_text))
    spec["milestones"][0]["where"] = "w"
    # diff-scoped enforcement
    new = {"N1": {"id": "N1", "state": "queued"}}
    assert any("no `roadmap`" in b for b in diff_problems(spec, new, {}, {}, {}, {"N1": 20}))
    assert diff_problems(spec, new, {}, {}, {}, {"N1": 5}) == []   # below the floor: exempt
    closing = {"N2": {"id": "N2", "state": "done", "roadmap": ["A"]}}
    assert any("writeback" in b for b in diff_problems(spec, closing, {"N2": {"id": "N2", "state": "queued", "roadmap": ["A"]}}, {}, {}, {"N2": 20}))
    closing["N2"]["writeback"] = {"roadmap": "none: tooling", "arch": "none: no contract change"}
    assert diff_problems(spec, closing, {"N2": {"id": "N2", "state": "queued", "roadmap": ["A"]}}, {}, {}, {"N2": 20}) == []
    assert any("new queue unit" in b for b in diff_problems(spec, {}, {}, {"RQ-20261013-1": {}}, {}, {}))
    assert diff_problems(spec, {}, {}, {"RQ-20261013-1": {"roadmap": "A"}}, {}, {}) == []
    print("roadmap_map self-test: ok")
    return 0


def backfill(path: str) -> int:
    mapping = json.loads(Path(path).read_text(encoding="utf-8"))
    ids = {m["id"] for m in load_spec()["milestones"]}
    done = 0
    for r in load_rows():
        ms = mapping.get(r["id"])
        if r.get("state") in LIVE_ROW and ms in ids and not as_list(r.get("roadmap")):
            subprocess.run([sys.executable, str(REPO / "scripts/ops/checklist.py"), "set", r["id"],
                            f'roadmap=["{ms}"]', "--by", "roadmap_map.backfill"], check=True, capture_output=True)
            done += 1
    print(f"backfill: set roadmap on {done} live rows")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--write-roadmap", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--base")
    ap.add_argument("--backfill", metavar="FILE")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.backfill:
        return backfill(a.backfill)
    if a.self_test:
        return self_test()
    if a.check:
        return check(a.base)
    spec = load_spec()
    built = build(spec, load_rows(), load_units())
    if a.render:
        print(render(spec))
    elif a.write_roadmap:
        write_roadmap(render(spec))
        print("ROADMAP.md live block written")
    else:
        print(report(spec, built, dt.datetime.now(dt.timezone.utc).date()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
