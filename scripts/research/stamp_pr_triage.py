#!/usr/bin/env python3
# wiring: .github/workflows/research-watchdog.yml (step "Triage conflicted stamp PRs"), tests/test_stamp_pr_triage.py
"""STAMP-PR-TRIAGE: dispose of conflicted dispatch-stamp PRs, scoped to the bot's own stamp branches.

WHY (manager, stamps@20261118T2342Z, PI-20261118-EFILLW47-0005). A dispatch stamp PR (`automation/research-queue-stamp-<run>-<n>`)
edits ONE line, `last_dispatched_at`, of each unit file the cycle fired. When another stamp PR, a re-arm or any PR that touches
the same unit file merges first, the rest go `dirty`; GitHub runs no pull_request checks on a conflicting PR, so its auto-merge
never has a green check, and nothing ever refreshed or closed it. Four sat open 3-4 h and the watchdog's only remedy (re-fire a
dispatch, which adopts the stamp) leaves the stale PR in place. Disposal by hand: 17 of 25 stamps were already <= main, 6 more
belonged to cadence-once units that already read not_due, 2 were deliberately unstamped producer_failed units.

PER UNIT, a stamp S against main's `last_dispatched_at` M (read from the checked-out main tree):
  superseded      M is a timestamp >= S.
  moot_once       M is a timestamp and the unit is `cadence: once`: any stamp reads "ran at ..." and not_due; S changes nothing.
  keep_unstamped  M is absent/null AND the unit's latest result row is `producer_failed`: an unstamped unit is what keeps it due
                  for a re-run, so landing S would drop it out of the queue. NEVER landed. (The exception, in code, with a test.)
  needs_land      anything else: S is newer than M and matters (a recurring cadence, or an unstamped unit with no failed result).

PER PR (only `automation/research-queue-stamp-*`, only `dirty` and older than --min-age-min -- never another branch):
  every unit superseded / moot_once / keep_unstamped  -> CLOSE with a per-unit comment.
  any needs_land                                      -> with --land: merge main into the branch resolving each unit file to
                                                         main's text with the stamp set to max(S, M), push (token must be able to
                                                         trigger CI), comment per unit. Without --land: report only.
DRY-RUN IS THE DEFAULT: without --live nothing is closed, commented or pushed; the decision table is printed (the log).
No halting: an unreadable PR / file / result is `could_not_look` and left alone; nothing here stops a pipeline.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple

_REPO = Path(__file__).resolve().parents[2]
STAMP_PREFIX = "automation/research-queue-stamp-"
QUEUE_PREFIX = "research/queue/"
STAMP_LINE = re.compile(r"^(last_dispatched_at:[ \t]*)([^\s#]+)([ \t]*(?:#.*)?)$", re.M)
SUPERSEDED, MOOT_ONCE, KEEP_UNSTAMPED, NEEDS_LAND, COULD_NOT_LOOK = (
    "superseded", "moot_once", "keep_unstamped", "needs_land", "could_not_look")
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def _ts(raw: Any) -> Optional[datetime]:
    if raw is None:
        return None
    s = str(raw).strip().strip("'\"")
    if not s or s.lower() in ("null", "none", "~"):
        return None
    try:
        d = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        return None
    return d if d.tzinfo else d.replace(tzinfo=timezone.utc)


def stamp_value(text: str) -> Optional[str]:
    """The raw `last_dispatched_at` value in a unit file's text, or None when the line is absent."""
    m = STAMP_LINE.search(text)
    return m.group(2).strip("'\"") if m else None


def patch_stamp(patch: str) -> Optional[str]:
    """The stamp a PR file patch ADDS (`+last_dispatched_at: ...`), or None."""
    m = re.search(r"^\+(last_dispatched_at:[ \t]*)([^\s#]+)", patch or "", re.M)
    return m.group(2).strip("'\"") if m else None


def cadence_of(text: str) -> Optional[str]:
    m = re.search(r"^cadence:[ \t]*['\"]?(\w+)", text, re.M)
    return m.group(1) if m else None


def set_stamp(text: str, value: str) -> str:
    """`text` with its last_dispatched_at set to `value` (quoted as the dispatcher writes it); added when absent."""
    new = f"last_dispatched_at: '{value}'"
    if STAMP_LINE.search(text):
        return STAMP_LINE.sub(lambda m: new, text, count=1)
    return text.rstrip("\n") + "\n" + new + "\n"


def classify_unit(stamp: Optional[str], main_text: Optional[str], latest_read_state: Optional[str]) -> Tuple[str, str]:
    """(kind, reason) for one stamp against main's file text and the unit's latest result read_state."""
    s = _ts(stamp)
    if s is None:
        return COULD_NOT_LOOK, f"stamp value unreadable ({stamp!r})"
    if main_text is None:
        return COULD_NOT_LOOK, "main's unit file could not be read"
    raw_m = stamp_value(main_text)
    m = _ts(raw_m)
    if m is not None and m >= s:
        return SUPERSEDED, f"main {m.isoformat()} >= stamp {s.isoformat()}"
    if m is not None and cadence_of(main_text) == "once":
        return MOOT_ONCE, f"cadence once and main already carries {m.isoformat()}: the unit reads 'ran at' either way"
    if m is None and latest_read_state == "producer_failed":
        return KEEP_UNSTAMPED, ("main has no stamp and the latest result is producer_failed: the unit must stay due for a "
                                "re-run; landing the stamp would drop it from the queue")
    return NEEDS_LAND, (f"stamp {s.isoformat()} is newer than main " + (m.isoformat() if m else "(no stamp)")
                        + " and matters (cadence " + str(cadence_of(main_text)) + ")")


def latest_read_state(unit_id: str, repo: Path = _REPO) -> Optional[str]:
    """read_state of the unit's newest result row on the checked-out tree; None when it has no rows."""
    rows = sorted((repo / "research" / "results" / unit_id).glob("*.jsonl")) if (repo / "research" / "results" / unit_id).is_dir() else []
    best: Tuple[str, Optional[str]] = ("", None)
    for f in rows:
        try:
            lines = [ln for ln in f.read_text(encoding="utf-8").splitlines() if ln.strip()]
            r = json.loads(lines[-1])
        except (OSError, ValueError, IndexError):
            continue
        key = str(r.get("generated_at") or "")
        if key >= best[0]:
            best = (key, r.get("read_state"))
    return best[1]


def decide_pr(files: List[dict], main_reader: Callable[[str], Optional[str]],
              result_state: Callable[[str], Optional[str]]) -> Dict[str, Any]:
    """Per-unit table + the PR-level action ('close' | 'land' | 'leave') for one PR's file list (gh `pulls/N/files`)."""
    units, other = [], []
    for f in files:
        name = f.get("filename") or ""
        if name.startswith(QUEUE_PREFIX) and name.endswith(".yaml"):
            uid = name[len(QUEUE_PREFIX):-len(".yaml")]
            st = patch_stamp(f.get("patch") or "")
            main_text = main_reader(name)
            kind, why = classify_unit(st, main_text, result_state(uid))
            units.append({"unit": uid, "path": name, "stamp": st, "main": stamp_value(main_text) if main_text else None,
                          "kind": kind, "reason": why})
        else:
            other.append(name)
    stray = [n for n in other if not (n.startswith(".github/merge-slots/") or n.startswith(".github/pr-landing/")
                                      or n.startswith(".github/pr-automerge-requests/"))]
    kinds = {u["kind"] for u in units}
    if not units or stray:
        action, why = "leave", ("no queue-unit stamp in the diff" if not units else f"touches non-stamp paths {stray[:3]}")
    elif COULD_NOT_LOOK in kinds:
        action, why = "leave", "at least one unit could not be classified"
    elif NEEDS_LAND in kinds:
        action, why = "land", "at least one stamp is newer than main and matters"
    else:
        action, why = "close", "every stamp is superseded, moot or deliberately unstamped"
    return {"action": action, "why": why, "units": units}


def comment_body(decision: Dict[str, Any], did: str) -> str:
    lines = [f"Stamp-PR triage (PI-20261118-EFILLW47-0005): {did}. This PR was conflicting with main and could not merge.", ""]
    for u in decision["units"]:
        lines.append(f"- `{u['unit']}`: **{u['kind']}** (stamp {u['stamp']}, main {u['main']}): {u['reason']}")
    return "\n".join(lines) + FOOTER


# ── GitHub / git effects ───────────────────────────────────────────────────────────────────────────────
def _gh(args: List[str], inp: Optional[str] = None) -> Optional[str]:
    try:
        p = subprocess.run(["gh", *args], capture_output=True, text=True, timeout=120, input=inp, check=False)
    except (OSError, subprocess.SubprocessError):
        return None
    return p.stdout if p.returncode == 0 else None


def _api(path: str) -> Optional[Any]:
    out = _gh(["api", path])
    if out is None:
        return None
    try:
        return json.loads(out)
    except ValueError:
        return None


def main_reader(repo_root: Path = _REPO) -> Callable[[str], Optional[str]]:
    def read(rel: str) -> Optional[str]:
        try:
            return (repo_root / rel).read_text(encoding="utf-8")
        except OSError:
            return None
    return read


def land_max(slug_repo: str, number: int, branch: str, decision: Dict[str, Any], token: str,
             repo_root: Path = _REPO) -> Tuple[bool, str]:
    """Merge main into `branch`, resolving every unit file to main's text with the stamp = max(stamp, main). Push with `token`."""
    wt = Path(os.environ.get("RUNNER_TEMP", "/tmp")) / f"stamp-triage-{number}"
    run = lambda *a, **k: subprocess.run(a, capture_output=True, text=True, cwd=k.get("cwd", str(repo_root)), timeout=300, check=False)  # noqa: E731
    url = f"https://x-access-token:{token}@github.com/{slug_repo}.git"
    if run("git", "fetch", "-q", url, f"+refs/heads/{branch}:refs/remotes/stamp/{branch}", "+refs/heads/main:refs/remotes/stamp/main").returncode:
        return False, "could not fetch the branch"
    if run("git", "worktree", "add", "-q", "--detach", str(wt), f"refs/remotes/stamp/{branch}").returncode:
        return False, "could not create the worktree"
    try:
        run("git", "merge", "--no-commit", "--no-ff", "refs/remotes/stamp/main", cwd=str(wt))   # conflicts expected; resolved below
        for u in decision["units"]:
            m = _ts(u["main"])
            s = _ts(u["stamp"])
            best = max([d for d in (m, s) if d is not None]) if (m or s) else None
            main_text = run("git", "show", f"refs/remotes/stamp/main:{u['path']}", cwd=str(wt)).stdout
            if best is None or not main_text:
                return False, f"cannot resolve {u['path']}"
            (wt / u["path"]).write_text(set_stamp(main_text, best.replace(microsecond=0).isoformat()), encoding="utf-8")
            run("git", "add", "--", u["path"], cwd=str(wt))
        left = run("git", "diff", "--name-only", "--diff-filter=U", cwd=str(wt)).stdout.split()
        if left:
            return False, f"unresolved conflicts remain: {left[:4]}"
        c = run("git", "-c", "user.name=github-actions[bot]", "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
                "commit", "-q", "-m", "stamp-pr-triage: merge main, resolve unit stamps to max(stamp, main)", cwd=str(wt))
        if c.returncode and "nothing to commit" not in (c.stdout + c.stderr):
            return False, "commit failed: " + (c.stderr or c.stdout)[:200]
        if run("git", "push", "-q", url, f"HEAD:refs/heads/{branch}", cwd=str(wt)).returncode:
            return False, "push refused"
        return True, "merged main and pushed"
    finally:
        run("git", "worktree", "remove", "--force", str(wt))


def triage(repo_slug: str, *, live: bool, land: bool, min_age_min: float, now: Optional[datetime] = None,
           token: str = "", out: Callable[[str], None] = print) -> List[Dict[str, Any]]:
    now = now or datetime.now(timezone.utc)
    prs = _api(f"repos/{repo_slug}/pulls?state=open&per_page=100")
    if prs is None:
        out("stamp-pr-triage: could not list open PRs (could_not_look); nothing done")
        return []
    results = []
    for p in prs:
        ref = str(((p.get("head") or {}).get("ref")) or "")
        if not ref.startswith(STAMP_PREFIX):
            continue                                        # ONLY the bot's stamp branches
        n = int(p["number"])
        created = _ts(p.get("created_at"))
        age = (now - created).total_seconds() / 60 if created else 0
        if age <= min_age_min:
            continue
        detail = _api(f"repos/{repo_slug}/pulls/{n}")
        state = (detail or {}).get("mergeable_state")
        if state != "dirty":
            out(f"#{n} {ref}: mergeable_state={state} (not dirty): left to auto-merge")
            continue
        files = _api(f"repos/{repo_slug}/pulls/{n}/files?per_page=100")
        if files is None:
            out(f"#{n} {ref}: could not read the PR files (could_not_look): left alone")
            continue
        d = decide_pr(files, main_reader(), latest_read_state)
        row = {"pr": n, "ref": ref, "age_min": round(age), **d, "live": live, "done": None}
        out(f"#{n} {ref} age {round(age)} min: {d['action'].upper()} ({d['why']})")
        for u in d["units"]:
            out(f"    {u['unit']:28s} stamp={u['stamp']} main={u['main']} -> {u['kind']}")
        if live and d["action"] == "close":
            if _gh(["pr", "comment", str(n), "--repo", repo_slug, "--body-file", "-"], comment_body(d, "closing as superseded")) is not None \
                    and _gh(["pr", "close", str(n), "--repo", repo_slug]) is not None:
                row["done"] = "closed"
        elif live and d["action"] == "land" and land and token:
            ok, why = land_max(repo_slug, n, ref, d, token)
            row["done"] = "landed" if ok else f"land_failed: {why}"
            if ok:
                _gh(["pr", "comment", str(n), "--repo", repo_slug, "--body-file", "-"],
                    comment_body(d, "merged main into the branch, stamps resolved to max(stamp, main); auto-merge can now run"))
        out(f"    -> {row['done'] or ('dry run: nothing done' if not live else 'reported only')}")
        results.append(row)
    return results


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY") or "")
    ap.add_argument("--live", action="store_true", help="close / comment (default: dry run, decisions printed only)")
    ap.add_argument("--land", action="store_true", help="with --live: also merge main into a PR whose stamps still matter")
    ap.add_argument("--min-age-min", type=float, default=30.0)
    args = ap.parse_args(argv)
    if not args.repo:
        print("stamp-pr-triage: no --repo / GITHUB_REPOSITORY", file=sys.stderr)
        return 2
    triage(args.repo, live=args.live, land=args.land, min_age_min=args.min_age_min,
           token=os.environ.get("STAMP_TRIAGE_TOKEN", ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
